const LanguageContext = createContext(null)

function getInitialLanguage() {
  const savedLanguage = localStorage.getItem('civicfix_language')
  if (savedLanguage === 'en' || savedLanguage === 'hi') return savedLanguage
  return navigator.language.toLowerCase().startsWith('hi') ? 'hi' : 'en'
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(getInitialLanguage)

  useEffect(() => {
    localStorage.setItem('civicfix_language', language)
    document.documentElement.lang = language
    document.title = language === 'hi'
      ? 'CivicFix AI | भारत में नागरिक रिपोर्टिंग'
      : 'CivicFix AI | Civic reporting in India'
  }, [language])

  const value = useMemo(() => ({
    language,
    locale: language === 'hi' ? 'hi-IN' : 'en-IN',
    toggleLanguage: () => setLanguage((current) => current === 'en' ? 'hi' : 'en'),
    t: (text) => language === 'hi'
      ? translations[text] || translations[text.toLowerCase()] || text
      : text,
  }), [language])

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>
}

export function useLanguage() {
  const context = useContext(LanguageContext)
  if (!context) throw new Error('useLanguage must be used within a LanguageProvider')
  return context
}
